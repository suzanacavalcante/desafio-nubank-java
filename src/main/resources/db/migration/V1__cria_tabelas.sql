-- Schema inicial: clientes e contatos (1 -> N).
-- Os tamanhos acompanham as constantes das entidades (Cliente.NOME_MAX, Contato.TELEFONE_MAX/EMAIL_MAX)
-- e os limites da validação de entrada. Não edite esta migration depois de aplicada: crie a V2.

CREATE TABLE clientes (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL
);

CREATE TABLE contatos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telefone   VARCHAR(30)  NOT NULL,
    email      VARCHAR(254) NOT NULL,
    cliente_id BIGINT       NOT NULL,
    CONSTRAINT fk_contatos_cliente
        FOREIGN KEY (cliente_id) REFERENCES clientes (id) ON DELETE CASCADE
);

-- O PostgreSQL não indexa a coluna da FK sozinho: sem isto, listar os contatos de um cliente
-- (GET /clientes/{id}/contatos) e apagar um cliente varrem a tabela inteira.
CREATE INDEX idx_contatos_cliente_id ON contatos (cliente_id);
